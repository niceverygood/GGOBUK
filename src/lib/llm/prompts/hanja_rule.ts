// 한자(漢字) 표기 공통 룰 — 페르소나 비종속 LLM 모듈에서 사용.
//
// daily/auspicious/coldread/compat/comic 같은 페르소나 종속이 아닌 모듈은
// LLM에 prompt를 보낼 때 한자 표기 가이드가 없으면 "庚子가 들어와 丁巳 일주
// 의 집중력이…" 같이 일반 사용자가 못 읽는 한자 단독 노출이 자주 발생한다.
// 이 공통 룰을 SYSTEM prompt에 박아 한글 우선 + 괄호 한자 형식으로 강제한다.
//
// ⚠️ interpret.ts와 chat.ts는 페르소나 스타일이 한자 룰을 자체적으로 정의하고
// 있으니(도사 모드는 한자 자유 등) 이 공통 룰을 import하지 마라.

export const HANJA_NOTATION_RULE = `[한자 표기 규칙 — 매우 중요]
- 60갑자(예: 庚子, 丁巳, 丙午)와 명리 술어(예: 比劫, 食傷, 印星, 通根, 格局, 用神)는 본문 안에 반드시 "한글 우선 + 괄호 한자" 형식으로 쓴다.
- ✅ 좋음: "경자(庚子)가 들어와 정사(丁巳) 일주의 집중력이…"
- ✅ 좋음: "오늘 정재가 들어와 일주의 집중력이…" (한자 생략도 OK)
- ❌ 나쁨: "庚子가 들어와 丁巳 일주의" (한자만 단독 노출 — 일반 사용자가 못 읽음)
- ❌ 나쁨: "丙午 세운 겁재 영향으로…" (한자만 단독)
- 같은 글자가 한 답변에서 반복되면 두 번째부터는 한자 괄호 생략 가능 (한글만으로 OK).
- 이 규칙은 모든 출력 텍스트 필드(요약·본문·bullet·표 셀)에 동일하게 적용.`;
