export const PERSONA_ORDER: PersonaKey[] = ['kkobuk', 'dosa', 'mudang', 'bosal'];

export function isPersonaKey(value: string): value is PersonaKey {
  return value === 'kkobuk' || value === 'dosa' || value === 'mudang' || value === 'bosal';
}

