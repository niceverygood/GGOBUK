/**
 * 사용자 데이터로부터 LLM에 주입할 signature behavior 후보 묶음을 만든다.
 *
 * 각 후보는 한 줄짜리 micro-observation. LLM은 이걸 그대로 베끼지 말고
 * 사용자의 다른 지표(일주, 격국, 진행 중 대운)와 결합해 그 사람만의
 * 문장으로 합성해야 한다 (premium_saju.ts 가이드 참조).
 */
export function buildSignatureBehaviors(params: {
  topSipsungGroup: string | null;
  iljiStage: string | null;
  yinYangTilt: 'yang_heavy' | 'yin_heavy' | 'balanced';
  weakestOhaeng: '목' | '화' | '토' | '금' | '수';
  /** 격국의 sipsung (예: '식신', '편관'). 없으면 null. */
  gyeokgukSipsung?: Sipsung | null;
  /** 일간 강약 라벨 (예: '신강', '신약'). */
  strengthLabel?: IlganStrength['label'] | null;
  /** 두드러진 신살 이름 배열. (예: ['양인살', '도화살']) */
  sinsalNames?: string[];
}): {
  fromSipsung: string[];
  fromIljiStage: string[];
  fromYinYang: string[];
  fromWeakOhaeng: string[];
  fromGyeokguk: string[];
  fromStrength: string[];
  fromSinsal: Array<{ name: string; lines: string[] }>;
} {
  const sinsalBuckets: Array<{ name: string; lines: string[] }> = [];
  if (params.sinsalNames && params.sinsalNames.length > 0) {
    // dedup + only known names
    const seen = new Set<string>();
    for (const name of params.sinsalNames) {
      if (seen.has(name)) continue;
      const lines = SINSAL_BEHAVIORS[name];
      if (lines && lines.length > 0) {
        sinsalBuckets.push({ name, lines });
        seen.add(name);
      }
    }
  }

  return {
    fromSipsung: params.topSipsungGroup
      ? SIPSUNG_GROUP_BEHAVIORS[params.topSipsungGroup] ?? []
      : [],
    fromIljiStage: params.iljiStage
      ? ILJI_STAGE_PATTERNS[params.iljiStage] ?? []
      : [],
    fromYinYang: YINYANG_TILT_PATTERNS[params.yinYangTilt] ?? [],
    fromWeakOhaeng: OHAENG_LACK_SIGNALS[params.weakestOhaeng] ?? [],
    fromGyeokguk: params.gyeokgukSipsung
      ? GYEOKGUK_BEHAVIORS[params.gyeokgukSipsung] ?? []
      : [],
    fromStrength: params.strengthLabel
      ? STRENGTH_BEHAVIORS[params.strengthLabel] ?? []
      : [],
    fromSinsal: sinsalBuckets,
  };
}

