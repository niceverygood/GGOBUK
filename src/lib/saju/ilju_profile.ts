/** Look up the 일주 profile for given gan/ji indices. */
export function iljuProfileOf(
  ganIdx: number,
  jiIdx: number,
): IljuProfile | null {
  const idx = gapjaIndexOf(ganIdx, jiIdx);
  const name = `${CHEONGAN[ganIdx]}${JIJI[jiIdx]}`;
  const hanja = `${CHEONGAN_HANJA[ganIdx]}${JIJI_HANJA[jiIdx]}`;
  const data = ILJU_DATA[name];
  if (!data) return null;
  return { index: idx, name, hanja, ...data };
}
